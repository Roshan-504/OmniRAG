import logging
from typing import Any, Dict, List, Optional
from google import genai
from google.genai import types
from app.config import settings

logger = logging.getLogger(__name__)

# Initialize Google GenAI client (NEW google.genai SDK)
client = genai.Client(api_key=settings.GEMINI_API_KEY)


def generate_rag_response(
    query: str,
    contexts: List[Dict[str, Any]],
    history: Optional[List[Any]] = None,
) -> Dict[str, Any]:
    """
    Synthesizes a strictly grounded, conversational answer to the user's question
    using Gemini 2.5 Flash grounded in retrieved context chunks and prior conversation history.
    """
    if not contexts:
        return {
            "answer": "I do not have any ingested knowledge to answer this question.",
            "sources": [],
        }

    # Extract unique source metadata
    unique_sources: List[Dict[str, str]] = []
    seen_sources = set()
    for ctx in contexts:
        source_name = ctx.get("source_name", "Unknown")
        source_type = ctx.get("source_type", "unknown")
        identifier = (source_name, source_type)
        if identifier not in seen_sources:
            seen_sources.add(identifier)
            unique_sources.append({
                "name": source_name,
                "type": source_type,
            })

    # Format the retrieved context blocks
    context_blocks: List[str] = []
    for ctx in contexts:
        source_name = ctx.get("source_name", "Unknown")
        source_type = ctx.get("source_type", "unknown")
        content = ctx.get("content", "").strip()
        context_blocks.append(f"---\nSource: {source_name} ({source_type})\n{content}\n---")

    context_block_str = "Contexts:\n" + "\n".join(context_blocks)

    # Format the last 4 messages of history to preserve conversational context
    history_str = "None"
    if history:
        recent_history = history[-4:]
        formatted_messages = []
        for msg in recent_history:
            role = msg.role if hasattr(msg, "role") else msg.get("role", "user")
            content = msg.content if hasattr(msg, "content") else msg.get("content", "")
            if content and content.strip():
                formatted_messages.append(f"{role.capitalize()}: {content.strip()}")
        if formatted_messages:
            history_str = "\n".join(formatted_messages)

    # Construct strict conversational prompt with historical context
    system_instruction = (
        "You are OmniRAG, a helpful and highly intelligent knowledge assistant. "
        "Answer the user's question using ONLY the provided context blocks below.\n\n"
        f"Previous Conversation Context:\n{history_str}\n\n"
        "CRITICAL INSTRUCTIONS:\n"
        "- Sound natural and conversational.\n"
        "- Use the 'Previous Conversation Context' to understand pronouns or follow-up questions, but ALWAYS ground your factual claims in the new 'Context Blocks'.\n"
        "- NEVER start your response with 'Based on the context'. Just answer directly.\n"
        "- If the context does not contain enough information, state clearly: 'I do not have enough information in my knowledge base to answer this question.'"
    )

    full_prompt = (
        f"{system_instruction}\n\n"
        f"{context_block_str}\n\n"
        f"User Question: {query.strip()}"
    )

    try:
        logger.info(f"Invoking Gemini (gemini-2.5-flash) for query: '{query[:60]}...'")
        response = client.models.generate_content(
            model="gemini-2.5-flash",
            contents=full_prompt,
        )

        answer_text = response.text.strip() if response.text else "No response generated by model."

        return {
            "answer": answer_text,
            "sources": unique_sources,
        }

    except Exception as exc:
        logger.error(f"Error during RAG generation: {exc}", exc_info=True)
        raise
